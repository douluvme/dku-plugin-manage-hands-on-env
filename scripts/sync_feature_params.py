#!/usr/bin/env python3
"""Snapshot the macro descriptors into python-lib for the webapp backend.

DSS runs a plugin webapp backend from a per-run copy that holds ``python-lib/``
and the webapp files only, so ``python-runnables/*/runnable.json`` is not
available at runtime. This script writes the ``meta`` and ``params`` of every
macro descriptor into ``python-lib/managehandsonenv/features/descriptor_data.py``,
which ``managehandsonenv.webapp.forms`` reads instead of the filesystem.

Usage:
    python3 scripts/sync_feature_params.py          # regenerate (``make sync``)
    python3 scripts/sync_feature_params.py --check  # exit 1 if the snapshot is stale
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python-lib"))

from managehandsonenv.descriptors import load_descriptor  # noqa: E402

TARGET = ROOT / "python-lib" / "managehandsonenv" / "features" / "descriptor_data.py"
HEADER = '''"""Snapshot of the macro descriptors (meta and params) for the webapp backend.

GENERATED by scripts/sync_feature_params.py from python-runnables/*/runnable.json.
Do not edit: run ``make sync`` after changing a descriptor. ``make check`` fails
while this file is stale.

DSS runs a plugin webapp backend from a copy that contains python-lib/ but not
python-runnables/, so the form builder reads this module instead of the files.
"""
import json

MACRO_DESCRIPTORS = json.loads(r\'\'\'
'''
FOOTER = "\'\'\')\n"


def collect():
    """``{folder: {"meta": ..., "params": [...]}}`` for every macro, sorted by folder."""
    snapshot = {}
    for descriptor in sorted((ROOT / "python-runnables").glob("*/runnable.json")):
        data = load_descriptor(descriptor)
        snapshot[descriptor.parent.name] = {"meta": data.get("meta", {}), "params": data.get("params", [])}
    return snapshot


def render(snapshot):
    body = json.dumps(snapshot, indent=4, ensure_ascii=False, sort_keys=True)
    if "'''" in body:
        raise ValueError("a descriptor contains ''' which the generated module cannot embed")
    return HEADER + body + "\n" + FOOTER


def main(argv):
    expected = render(collect())
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if "--check" in argv:
        if current == expected:
            print("descriptor snapshot is up to date: {}".format(TARGET.relative_to(ROOT)))
            return 0
        print("ERROR: {} is stale; run `make sync` (python3 scripts/sync_feature_params.py)".format(
            TARGET.relative_to(ROOT)))
        return 1
    if current == expected:
        print("unchanged: {}".format(TARGET.relative_to(ROOT)))
    else:
        TARGET.write_text(expected, encoding="utf-8")
        print("wrote {}".format(TARGET.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
